//! Команды крейта.
//!
//! Крейт объявляет здесь свои команды, а `claxis-commands` регистрирует их под
//! именем из объявления: `edit::undo` становится `:std::edit::undo`. Список
//! живёт один раз, у крейта: кто-то другой не придумывает команды за него.
//!
//! Объявление не тянет за собой зависимости: это просто список строк, чтобы
//! крейт перечислил свои команды, не зная про крейт команд. Собирает их
//! бинарный крейт, `crate::router::commands`.
//!
//! Что команда делает — написано тут, в комментариях. Это текст для
//! разработчика, а не для человека: показывать его будут переводы, поэтому в
//! списке нет ни одного слова, которое человек видит.
//!
//! Команда попадает сюда, только когда она уже работает. Объявленная, но
//! невыполняемая команда — обещание, которое редактор не сдержит.

