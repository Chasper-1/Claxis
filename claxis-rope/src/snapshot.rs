//! Куда уходит снятый снапшот.

use std::path::Path;

use crate::history::History;

/// Приёмник снапшота.
///
/// Буфер ничего не знает про диск: он отдаёт текст, историю и имя документа,
/// а что с этим делать — решает приёмник. Поэтому буфер не зависит ни от
/// стора, ни от файловой системы, а снапшот куда угодно пишется снаружи.
pub trait SnapshotSink: std::fmt::Debug {
    /// Документ снят: текст нужно сохранить для будущего восстановления.
    ///
    /// Вызывается уже после того, как снапшот стал новым `Original`, то есть
    /// текст тут окончательный. История идёт рядом с текстом: отменять правки
    /// после перезапуска должно быть можно, поэтому снапшот без истории
    /// бесполезен.
    ///
    /// Ошибка не возвращается: сохранение снапшота не обязано ломать правку —
    /// потеря кеша не должна стоить пользователю работы.
    fn accept(&mut self, file: &Path, text: &[u8], history: &History);
}

/// Приёмник, который ничего не делает. По умолчанию снапшот никуда не пишется.
#[derive(Clone, Copy, Debug, Default)]
pub struct NullSink;

impl SnapshotSink for NullSink {
    fn accept(&mut self, _file: &Path, _text: &[u8], _history: &History) {}
}
