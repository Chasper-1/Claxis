//! Ядро редактора: курсор, выделение, токены и карта строк.
//!
//! Курсор хранит только две байтовые позиции: якорь и голову. Выделение — это
//! неравенство позиций, отдельного хранилища у него нет. Границы графем и
//! токенов не кэшируются: они считаются на каждом шаге по куску текста.
//!
//! Крейт работает с байтами и не знает про терминал, отрисовку, ширину
//! символов и диск. Документ тоже не нужен: вызывающий отдаёт строку, в
//! которой стоит курсор.

pub mod commands;
pub mod cursor;
pub mod line;
pub mod token;

pub use commands::COMMANDS;
pub use cursor::{Cursor, Position};
pub use line::LineMap;
pub use token::{JumpMode, Token, TokenFilter, TokenIter, TokenKind, tokens};
