//! Значения по умолчанию для конфига редактора.
//!
//! Это то, что крейт конфига возьмёт при первом запуске и запишет в конфиг
//! со всеми ключами разом. Правило: **любая настройка, которая когда-либо
//! задумана, обязана здесь быть**. Настройки, которые кодом пока не
//! используются, тоже присутствуют, но выключены — их запись помечается
//! `active: false`, и генератор конфига выводит их закомментированными.
//!
//! Здесь только настройки документа. Настройки других крейтов живут в них:
//! снапшоты — в `claxis-disk`, ввод — в `claxis-input`.
//!
//! ```toml
//! # [General]
//! # Сколько записей правки держать в памяти до снапшота.
//! history_depth = 8192
//! ```
//!
//! Потолка у настройки нет: история растёт по мере правок, а это число
//! говорит только, когда пора снять снапшот. Настоящий предел — память.

/// Одна настройка по умолчанию: значение, ключ и комментарий для конфига.
#[derive(Clone, Copy, Debug)]
pub struct Default<T> {
    /// Ключ в секции конфига.
    pub key: &'static str,
    /// Значение по умолчанию.
    pub value: T,
    /// Комментарий к ключу, попадает в конфиг как есть.
    pub comment: &'static str,
    /// Используется ли настройка кодом сейчас.
    ///
    /// `false` — настройка задумана, но ещё не подключена. Генератор
    /// конфига выводит такую строку закомментированной.
    pub active: bool,
}

impl<T> Default<T> {
    /// Настройка, которая уже используется кодом.
    pub const fn used(key: &'static str, value: T, comment: &'static str) -> Self {
        Self {
            key,
            value,
            comment,
            active: true,
        }
    }
}

/// Настройки документа.
pub mod buffer {
    use super::Default;

    /// Глубина истории в записях: сколько правок держится до снапшота.
    pub const HISTORY_DEPTH: Default<u32> = Default::used(
        "history_depth",
        crate::document::DEFAULT_DEPTH,
        "Сколько записей правки держать в памяти до снапшота.",
    );

    /// Все настройки раздела.
    pub const ALL: &[Default<u32>] = &[HISTORY_DEPTH];
}
