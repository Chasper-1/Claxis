//! Темы.
//!
//! Тема — файл в папке, и имя файла значит название темы. Тем может быть
//! сколько угодно, и пользователь сам кладёт их файлы: тема появляется без
//! пересборки редактора.
//!
//! Содержимое файла темы здесь **не** разбирается. Крейт отвечает на два
//! вопроса, которые задаёт конфиг: какие темы есть и есть ли тема с таким
//! именем. Отдельно разбирается только код цвета: он нужен и теме, и
//! подсветке конфига.

