//! Клавиши как позиции, раскладки, модификаторы, составление, лидер, отмена.
//!
//! Крейт создан заранее, чтобы настройки ввода жили здесь, а не в буфере.
//! Пока реализации нет: правило «любая задуманная настройка обязана быть
//! записана» требует, чтобы она существовала до того, как её начнут читать.

/// Настройки ввода.
///
/// Значения по умолчанию, которые крейт конфига возьмёт при первом запуске.
/// Ключи станут секцией `[Input]` в конфиге редактора.
pub mod defaults {
    /// Окно нажатия и удержания, миллисекунды. По умолчанию 200.
    ///
    /// Нажал и отпустил в пределах окна — обычное одиночное действие. Только
    /// нажал, а отпустил позже окна — удержание: включается режим, и всё, что
    /// набирается, пока клавиша удерживается, применяется при отпускании.
    ///
    /// Окно действует только на клавиши с двумя назначениями. На все клавиши
    /// подряд оно распространяться не может: тогда каждый введённый символ
    /// приходил бы с задержкой в окно и печатать было бы невозможно.
    ///
    /// Ключ: `tap_hold_ms`.
    pub const TAP_HOLD_MS: u32 = 200;
}

/// Каждая настройка здесь описана и имеет значение.
#[cfg(test)]
mod tests {
    use super::defaults::TAP_HOLD_MS;

    #[test]
    fn tap_hold_window_is_usable() {
        // Ноль означал бы, что удержание невозможно и второй смысл клавиши
        // недоступен вообще.
        const { assert!(TAP_HOLD_MS > 0, "окно должно быть больше нуля") }
    }

    #[test]
    fn tap_hold_window_is_not_absurd() {
        // Слишком большое окно — та же невозможность набрать текст, только
        // медленнее. 200 мс это обычное значение для split-клавиатур.
        const {
            assert!(
                TAP_HOLD_MS <= 1000,
                "окно больше секунды сделает ввод невозможным"
            )
        }
    }
}
