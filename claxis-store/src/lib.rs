//! его можно удалить и потерять без вреда для текста.
//!
//! Лежит в кеше ОС, обычно `~/.cache/claxis/`. Данные служебные, формат
//! рассчитан на машину, а не на человека, поэтому это SQLite: он держит
//! несколько процессов одновременно и переживает падение при записи.

