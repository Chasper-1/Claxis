//! Служебные данные вне документа: снапшоты истории, состояние вкладок.
//!
//! SQLite в кеше ОС. Крейт ничего не знает про буфер: он умеет только
//! складывать и доставать снапшоты.

/// Сколько снапшотов одного файла держать в кеше. По умолчанию 3.
///
/// Старые вытесняются. Кольцо одно на файл, в одной транзакции.
///
/// Ключ: `keep`.
pub const KEEP: u32 = 3;

/// Хранить ли снапшоты на диск между запусками. По умолчанию true.
///
/// Работает: буфер отдаёт снятый снапшот приёмнику, сессия пишет его сюда.
///
/// Ключ: `persist`.
pub const PERSIST: bool = true;

/// Настройки согласованы с тем, как крейт работает на самом деле.
#[cfg(test)]
mod tests {
    use super::{KEEP, PERSIST};

    #[test]
    fn keep_is_sane() {
        // Ноль снапшотов лишает смысла кеш, единица не защищает историю.
        const {
            assert!(KEEP >= 1, "нулевой keep означает, что кеш не работает")
        }
    }

    #[test]
    fn persist_is_the_default() {
        // Иначе история не пережила бы перезапуск, а это половина смысла.
        const {
            assert!(
                PERSIST,
                "хранить снапшоты между запусками должно быть включено"
            )
        }
    }
}
