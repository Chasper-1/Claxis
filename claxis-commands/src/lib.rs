//! Система команд: имена, реестр, командная строка, алиасы и привязки.
//!
//! Крейт ничего не выполняет и ничего не знает про терминал и редактор. Он
//! отвечает на три вопроса:
//!
//! * какие команды существуют — [`Registry`];
//! * на что разворачивается напечатанное — [`Bindings`], [`Alias`], [`Level`];
//! * что человек написал в командной строке — [`CommandLine`].
//!
//! Имена команд не переводятся: это внутренняя логика, а не интерфейс.
//! Переводится то, что человек видит: подсказки и сообщения об ошибках.
//!
//! Раскладки здесь нет: алиас сравнивается как напечатан, а хоткей приходит
//! уже позицией клавиши. Зависимости у крейта тоже нет — только текст для
//! подстановки значений в сообщения.

pub mod alias;
pub mod bindings;
pub mod error;
pub mod level;
pub mod messages;
pub mod name;
pub mod registry;

pub use alias::Alias;
pub use bindings::Bindings;
pub use error::Error;
pub use level::Level;
