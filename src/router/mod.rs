//! Маршрутизатор: связывает крейты между собой.
//!
//! Через него проходят все вызовы между крейтами. Связи не линейные: почти
//! всё зависит от почти всего, и линейная схема быстро превратилась бы в
//! спагети. Здесь всё держится рядом и видно, что с чем связано.
//!
//! На производительность это не влияет: инлайнит компилятор, а не структура
//! модулей.
//!
//! # Что с чем связано
//!
//! ```text
//!   claxis-config ──► claxis-i18n      подписи и комментарии из перевода
//!         │
//!         ▼
//!   session ──► claxis-buffer          документ и снятые снапшоты
//!         ├──► claxis-core            карта строк и курсор
//!         └──► claxis-disk            всё, что пишется на диск
//!
//!   editor ──► session                 всё вместе, верхний уровень
//!          └─► claxis-term            события терминала
//! ```
//!
//! Правило одно: крейт не знает о других напрямую. Всё, что связано, связано
//! здесь — иначе связи расползутся по кодам, и найти их станет невозможно.
//!
//! Этот файл только связывает модули: код лежит в файлах рядом.
//!
//! # Как читать
//!
//! | Файл | Что связывает |
//! | --- | --- |
//! | [`session`] | буфер и хранилище: открыть документ, снять снапшот на диск |
//! | [`document`] | открытый документ: текст, карта строк, статистика |
//! | [`lines`] | карта строк документа: едет вместе с текстом |
//! | [`sink`] | приёмник снапшота: кольцо на диске и проверка записи |
//! | [`clock`] | источник времени |
//! | [`error`] | ошибки сессии |
//! | [`stats`] | что человек делал: символы, нажатия, занятая история |
//! | [`cycle`] | цикл: события терминала идут в документ |
//! | [`settings`] | конфиг и перевод: язык, значения настроек, комментарии |
//! | [`editor`] | всё вместе: то, с чего начинается запуск |

