//! Работа с диском: запись, чтение, наблюдение, кеш.
//!
//! Крейт один на весь проект, и это не украшение, а требование. Всё, что
//! касается диска, проходит здесь: запись файлов, чтение, слежение за
//! изменениями, кеш снапшотов. Крейт ничего не проверяет и ничего не решает:
//! он делает одну вещь — пишет правильно.
//!
//! Правильно — значит атомарно, через временный файл с переименованием.
//! Читатель никогда не увидит наполовину записанный конфиг, а упавшая запись
//! не оставит после себя мусор.
//!
//! Кто может сохранить — решает вызывающий. Спрашивает ли конфиг, можно ли
//! такое значение, держит ли буфер глубину истории — это дело крейта, который
//! знает про конфиг или про буфер. Сюда приходят с готовым решением.
//!
//! Раскладку на диске крейт не знает. Где лежит конфиг — дело `claxis-config`,
//! сюда приносят готовый путь.

pub mod defaults;
