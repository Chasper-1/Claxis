//! Служебные данные вне документа: снапшоты истории, состояние вкладок.
//!
//! Всё это — кеш, его можно удалить и потерять без вреда для текста. Формат
//! рассчитан на машину, а не на человека, поэтому это SQLite: держит несколько
//! процессов одновременно и переживает падение при записи.

/// Имя каталога кеша внутри кеша операционной системы.
pub const CACHE_DIR: &str = "claxis";

/// Сколько снапшотов одного файла держать в кеше. По умолчанию 3.
///
/// Старые вытесняются. Кольцо одно на файл, в одной транзакции.
///
/// Ноль допустим: снапшоты не сохраняются, но история при этом не
/// уничтожается — она живёт в памяти до перезапуска. Если история не нужна
/// между запусками, это честный способ её не тащить на диск.
///
/// Больше 255 смысла нет: столько снапшотов одного файла не набирается.
///
/// Ключ: `keep`.
pub const KEEP: u8 = 3;

/// Хранить ли снапшоты на диск между запусками. По умолчанию true.
///
/// Работает: буфер отдаёт снятый снапшот приёмнику, сессия пишет его сюда.
///
/// Ключ: `persist`.
pub const PERSIST: bool = true;

/// Настройки согласованы с тем, как крейт работает на самом деле.
#[cfg(test)]
mod tests {
    use super::{CACHE_DIR, KEEP, PERSIST};

    #[test]
    fn keep_is_sane() {
        // Ноль снапшотов лишает смысла кеш, единица не защищает историю.
        const {
            assert!(KEEP >= 1, "нулевой keep означает, что кеш не работает")
        }
    }

    #[test]
    fn persist_is_the_default() {
        // Иначе история не пережила бы перезапуск, а это половина смысла.
        const {
            assert!(
                PERSIST,
                "хранить снапшоты между запусками должно быть включено"
            )
        }
    }

    #[test]
    fn the_cache_directory_has_a_name() {
        // Кеш без имени не найти: он обязан называться так же, как редактор.
        const {
            assert!(!CACHE_DIR.is_empty(), "у каталога кеша должно быть имя")
        }
        assert_eq!(CACHE_DIR, "claxis");
    }

    #[test]
    fn the_default_path_uses_the_cache_directory_name() {
        // Раскладка кеша живёт здесь, а не по дороге в вызывающем коде.
        assert!(crate::StorePaths::from_env().dir.ends_with(CACHE_DIR));
    }
}
